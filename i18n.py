def tr(lang, key, **kwargs):
    """Translate key to lang, falling back to Russian."""
    table = STRINGS.get(lang) or STRINGS["ru"]
    tpl = table.get(key) or STRINGS["ru"].get(key, key)
    if kwargs:
        return tpl.format(**kwargs)
    return tpl


